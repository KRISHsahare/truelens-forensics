"""A generated corpus, for verifying this pipeline without a multi-gigabyte download.

**What this is and what it is not.** ``train_cnn.py`` and ``evaluate_cnn.py`` are only useful
against a real dataset, and the real datasets are gated downloads that need an account and an
agreement nobody has signed here. That leaves a verification problem: how do you prove the
training loop, the checkpoint format, the Grad-CAM hook, the metrics writer and the fusion
calibrator all work, on a laptop, before someone with credentials runs them for real?

This module answers it. It renders two classes whose *measurable statistics* differ for the same
reason the real classes do — a photographic capture has a sensor-noise floor and a 1/f² spectral
tail, a synthesised image has neither — and it is honest about being a texture task, not a
deepfake task. A model trained here has a real accuracy figure on this corpus and no claim about
the world. That is why the scripts write to a scratch directory by default and why
``artifacts/model.pt`` is *not* produced from it: shipping weights fitted on procedurally smooth
gradients into a service that scores people's holiday photographs would turn a documented gap into
an undocumented confidence.

Uses: CI, a fresh checkout, and anyone who wants to read the pipeline end to end without waiting
on a download.
"""

from __future__ import annotations

import numpy as np

__all__ = ["PROVENANCE", "render", "render_pair"]

#: Copied into ``metrics.json``'s ``dataset.note`` by the scripts that use this module, so a
#: generated evaluation can never be read as a real-world one.
PROVENANCE = (
    "Synthetic texture corpus generated by ml/truelens_ml/synthetic.py. The classes differ in "
    "sensor-noise floor and spectral slope, which is a real signal and a narrow one: these numbers "
    "validate the training, checkpoint, evaluation and export pipeline end to end. They are NOT an "
    "accuracy claim about photographs, generators, or deepfakes."
)

_SIZES = (256, 320, 448)


def _fractal_noise(rng: np.random.Generator, size: int, *, alpha: float) -> np.ndarray:
    """Pink/brown noise by spectral synthesis: amplitude ~ 1/f**alpha, random phase.

    ``alpha=1`` is the texture family of a natural photograph; ``alpha=2`` is what a diffusion
    model's output looks like before any sensor noise is mixed in — smoother, with the high band
    rolled off. This is the same radial-spectrum measurement the ``frequency`` analyser makes,
    which is deliberate: the generated corpus should be hard for the same reason the real task is.
    """
    h = w = size
    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.fftfreq(w)[None, :]
    radius = np.sqrt(fx * fx + fy * fy)
    radius[0, 0] = 1.0  # the DC bin is set separately; dividing by zero would poison the spectrum
    amplitude = 1.0 / (radius ** (alpha / 2.0))
    phase = np.exp(2j * np.pi * rng.random((h, w)))
    spectrum = amplitude * phase
    field = np.fft.ifft2(spectrum).real
    return _unit(field)


def _unit(a: np.ndarray) -> np.ndarray:
    lo, hi = float(a.min()), float(a.max())
    return (a - lo) / (hi - lo + 1e-9)


def _scene(rng: np.random.Generator, size: int) -> np.ndarray:
    """A low-frequency "scene" plus mid-frequency structure, float in [0, 1]."""
    base = _fractal_noise(rng, size, alpha=1.0)
    detail = _fractal_noise(rng, max(32, size // 4), alpha=1.6)
    import cv2

    detail = cv2.resize(detail, (size, size), interpolation=cv2.INTER_CUBIC)
    lum = 0.62 * base + 0.38 * detail
    return _unit(lum)


def render(rng: np.random.Generator, *, kind: str, size: int = 224) -> np.ndarray:
    """One uint8 RGB image of the requested class.

    Both classes get a random geometry and a random amount of the *other* class's nuisance
    factors, so a detector cannot win by reading the file extension, the canvas size, or the mere
    presence of JPEG quantisation — the three shortcuts that make a hand-made corpus score 1.0 and
    teach nothing.
    """
    canvas = int(rng.choice(_SIZES))
    scene = _scene(rng, canvas)

    # Three colour channels from one luminance field with independent low-frequency tints, so the
    # images are RGB rather than grey-with-a-copy-of-it.
    img = np.stack([scene,
                    _unit(scene * 0.85 + _fractal_noise(rng, canvas, alpha=2.0) * 0.15),
                    _unit(scene * 0.7 + _fractal_noise(rng, canvas, alpha=2.4) * 0.3)],
                   axis=-1)
    img = (img * 255.0).astype(np.float32)

    if kind == "real":
        sigma = float(rng.uniform(1.6, 7.0))          # sensor noise, in 8-bit levels
        img = img + rng.normal(0.0, sigma, img.shape)
        if rng.random() < 0.25:                        # shot in low light: noisier
            img = img + rng.normal(0.0, rng.uniform(4.0, 12.0), img.shape)
    else:
        # A synthesised frame: the noise floor is absent, and a small fraction carry the periodic
        # fingerprint an upsampling layer leaves behind.
        if rng.random() < 0.35:
            img = img + rng.normal(0.0, rng.uniform(0.4, 1.4), img.shape)
        if rng.random() < 0.45:
            img = _checkerboard(img, period=int(rng.choice([2, 4, 8])))

    img = np.clip(img, 0, 255).astype(np.uint8)
    if canvas != size:
        import cv2

        img = cv2.resize(img, (size, size), interpolation=cv2.INTER_AREA)
    return np.ascontiguousarray(img)


def _checkerboard(img: np.ndarray, *, period: int) -> np.ndarray:
    h, w, _ = img.shape
    yy = (np.arange(h)[:, None] // period) % 2
    xx = (np.arange(w)[None, :] // period) % 2
    grid = ((yy + xx) % 2).astype(np.float32)[..., None] - 0.5
    return img + grid * 2.2


def render_pair(rng: np.random.Generator, *, size: int = 224) -> tuple[np.ndarray, np.ndarray]:
    """``(real, fake)`` for one prompt-equivalent, used by the corpus writer."""
    return (render(rng, kind="real", size=size), render(rng, kind="fake", size=size))
